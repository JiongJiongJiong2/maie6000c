import io
from uuid import uuid4

from PIL import Image

from services.common.config import get_settings
from services.common.search_models import ReferenceAsset
from services.common.storage import atomic_write, prepare_storage, sha256


def test_library_is_opt_in_and_honors_authentication(client, monkeypatch):
    assert client.get("/demo-library").status_code == 404
    monkeypatch.setenv("ENABLE_DEMO_LIBRARY", "true")
    monkeypatch.setenv("DEVICE_TOKEN", "example-token")
    get_settings.cache_clear()
    assert client.get("/demo-library").status_code == 401
    result = client.get("/demo-library", headers={"Authorization": "Bearer example-token"})
    assert result.json() == {"examples": []}


def test_example_is_an_actual_frame_without_exposing_storage_paths(client, db_session, monkeypatch):
    monkeypatch.setenv("ENABLE_DEMO_LIBRARY", "true")
    get_settings.cache_clear()
    prepare_storage()
    output = io.BytesIO()
    Image.new("RGB", (16, 16), "red").save(
        output,
        format="GIF",
        save_all=True,
        append_images=[Image.new("RGB", (16, 16), "blue")],
        duration=100,
        loop=0,
    )
    data = output.getvalue()
    atomic_write(get_settings().reference_root, "sample.gif", data)
    asset = ReferenceAsset(
        id=str(uuid4()),
        sha256=sha256(data),
        title="Example",
        source_reference="generated by test",
        permission_note="original test",
        gif_path="sample.gif",
        frame_count=2,
        corpus_version="test",
    )
    db_session.add(asset)
    db_session.commit()
    example = client.get("/demo-library").json()["examples"][0]
    assert set(example) == {"id", "title", "screenshot_url"}
    image = client.get(example["screenshot_url"])
    assert image.status_code == 200 and image.headers["content-type"] == "image/png"
    with Image.open(io.BytesIO(image.content)) as decoded:
        assert decoded.getpixel((0, 0)) == (255, 0, 0)
    assert client.get(f"/demo-library/{uuid4()}/screenshot").status_code == 404
