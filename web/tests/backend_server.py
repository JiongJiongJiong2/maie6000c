"""Disposable real-backend browser harness. NEVER use as an application server.

Uses actual search routes, SQLite persistence, worker state transitions and media
validation. Only retrieval results are injected, with a generated two-frame GIF.
All data is created under TemporaryDirectory; no application database is touched.
"""

from __future__ import annotations

import importlib.util
import io
import os
from pathlib import Path
import sys
import tempfile
from uuid import UUID, uuid4

ROOT = Path(__file__).resolve().parents[2]
BACKEND_ROOT = Path(os.environ.get("WEB_BACKEND_ROOT", str(ROOT))).resolve()
sys.path.insert(0, str(BACKEND_ROOT))
# The actual worker launches a Python subprocess; it must import this backend too.
os.chdir(BACKEND_ROOT)
temporary = tempfile.TemporaryDirectory(prefix="memeretrieve-web-test-")
storage = Path(temporary.name)
os.environ.update(
    DATABASE_URL=f"sqlite:///{storage / 'browser.db'}",
    MEDIA_ROOT=str(storage / "media"),
    REFERENCE_ROOT=str(storage / "reference"),
    MODEL_CACHE_ROOT=str(storage / "models"),
    DEVICE_TOKEN="web-test-token",
    LOG_LEVEL="WARNING",
)


def build_app():
    from fastapi import HTTPException
    from PIL import Image, ImageDraw
    from sqlalchemy import func, select

    try:
        from services.api.app.main import app
        from services.common.config import get_settings
        from services.common.db import Base, get_engine, get_session_factory
        from services.common.search_models import (
            ReferenceAsset,
            ReviewDecision,
            SearchJob,
            SearchRequest,
        )
        from services.common.search_schemas import RetrievalMatch, RetrievalResult
        from services.common.storage import atomic_write, prepare_storage, sha256
        from services.worker.app import search_worker
    except ImportError as exc:
        raise SystemExit(
            "W07 backend is required. Set WEB_BACKEND_ROOT to its local checkout."
        ) from exc

    # Mount the current web implementation even when testing an unmerged backend.
    if not any(getattr(route, "path", None) == "/web/" for route in app.routes):
        spec = importlib.util.spec_from_file_location(
            "web_under_test", ROOT / "services/api/app/web.py"
        )
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        app.include_router(module.router)

    Base.metadata.create_all(get_engine())
    prepare_storage()
    frames = []
    for color, offset in [("#e6e8d9", 0), ("#f5d6bd", 10)]:
        frame = Image.new("RGB", (160, 160), color)
        draw = ImageDraw.Draw(frame)
        draw.ellipse((37, 40 + offset, 51, 54 + offset), fill="#46563c")
        draw.ellipse((106, 40 + offset, 120, 54 + offset), fill="#46563c")
        draw.arc((45, 62, 115, 114), 0, 180, fill="#46563c", width=5)
        draw.text((40, 137), "TEST FIXTURE", fill="#46563c")
        frames.append(frame)
    buffer = io.BytesIO()
    frames[0].save(
        buffer, format="GIF", save_all=True, append_images=frames[1:], duration=400, loop=0
    )
    data = buffer.getvalue()
    atomic_write(get_settings().reference_root, "fixture.gif", data)
    asset_id = str(uuid4())
    factory = get_session_factory()
    with factory() as db:
        db.add(
            ReferenceAsset(
                id=asset_id,
                sha256=sha256(data),
                title="Generated browser fixture",
                source_reference="web/tests/backend_server.py",
                permission_note="Generated by test",
                gif_path="fixture.gif",
                frame_count=2,
                corpus_version="web-test-fixture",
            )
        )
        db.commit()

    @app.get("/__test__/crop")
    def crop():
        from fastapi.responses import Response

        output = io.BytesIO()
        frames[0].save(output, format="PNG")
        return Response(output.getvalue(), media_type="image/png")

    @app.post("/__test__/complete/{mode}")
    def complete(mode: str):
        if mode not in {"candidates", "no_candidates", "unavailable"}:
            raise HTTPException(status_code=400)
        with factory() as db:
            job = search_worker.claim_next_search_job(db)
            if job is None:
                raise HTTPException(status_code=409, detail="No pending job")
            job_id = job.id
        if mode == "unavailable":
            # Exercise the real missing-retrieval path, not a fake HTTP error.
            try:
                search_worker.process_search_job(job_id)
            except search_worker.RetrievalError as exc:
                with factory() as db:
                    search_worker.fail_job(db, job_id, exc.code, str(exc))
        else:
            result = RetrievalResult(
                matches=[RetrievalMatch(reference_asset_id=UUID(asset_id), score=0.87)]
                if mode == "candidates"
                else [],
                model_version="injected-test-result-not-inference",
                corpus_version="web-test-fixture",
            )
            search_worker.process_search_job(job_id, lambda _: result)
        return {"job_id": job_id, "fixture": True}

    @app.get("/__test__/counts/{request_id}")
    def counts(request_id: str):
        with factory() as db:
            job_ids = select(SearchJob.id).where(SearchJob.request_id == request_id)
            return {
                "requests": db.scalar(
                    select(func.count())
                    .select_from(SearchRequest)
                    .where(SearchRequest.id == request_id)
                ),
                "jobs": db.scalar(
                    select(func.count())
                    .select_from(SearchJob)
                    .where(SearchJob.request_id == request_id)
                ),
                "reviews": db.scalar(
                    select(func.count())
                    .select_from(ReviewDecision)
                    .where(ReviewDecision.job_id.in_(job_ids))
                ),
            }

    return app


if __name__ == "__main__":
    import uvicorn

    try:
        uvicorn.run(build_app(), host="127.0.0.1", port=8766, log_level="warning")
    finally:
        temporary.cleanup()
